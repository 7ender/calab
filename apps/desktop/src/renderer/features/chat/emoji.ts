export function searchEmoji(q: string): string[] {
  const needle = q.trim().toLowerCase();
  if (!needle) return [];
  const out: string[] = [];
  for (const [e, words] of Object.entries(KEYWORDS)) if (words.split(' ').some((w) => w.startsWith(needle))) out.push(e);
  return out;
}
